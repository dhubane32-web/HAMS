#!/usr/bin/env node
/**
 * Embeds an immutable build id into the client bundle (cache-bust on every deploy).
 * Run before `next build` in CI/Vercel.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createHash } from 'crypto';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const libDir = path.join(root, 'lib');
const publicDir = path.join(root, 'public');

const gitSha = (
  process.env.VERCEL_GIT_COMMIT_SHA ||
  process.env.GITHUB_SHA ||
  process.env.RAILWAY_GIT_COMMIT_SHA ||
  ''
).trim();

const buildTime = new Date().toISOString();
const navConfigVersion = String(process.env.HAMS_NAV_CONFIG_VERSION || '2').trim();

const buildId = gitSha
  ? `${gitSha.slice(0, 12)}-${createHash('sha256').update(`${gitSha}:${buildTime}:${navConfigVersion}`).digest('hex').slice(0, 8)}`
  : `local-${Date.now().toString(36)}`;

const generatedTs = `// AUTO-GENERATED by scripts/generate-build-meta.mjs — do not edit.
export const APP_BUILD_ID = ${JSON.stringify(buildId)};
export const APP_BUILD_TIME = ${JSON.stringify(buildTime)};
export const NAV_CONFIG_VERSION = ${JSON.stringify(navConfigVersion)};
`;

fs.mkdirSync(libDir, { recursive: true });
fs.mkdirSync(publicDir, { recursive: true });
fs.writeFileSync(path.join(libDir, 'build-meta.generated.ts'), generatedTs, 'utf8');
fs.writeFileSync(path.join(publicDir, 'build-id.txt'), `${buildId}\n`, 'utf8');

const envBuild = [
  `NEXT_PUBLIC_APP_BUILD_ID=${buildId}`,
  `NEXT_PUBLIC_NAV_CONFIG_VERSION=${navConfigVersion}`,
  `NEXT_PUBLIC_APP_BUILD_TIME=${buildTime}`
].join('\n');

fs.writeFileSync(path.join(root, '.env.build.meta'), `${envBuild}\n`, 'utf8');
fs.writeFileSync(path.join(root, '.env.production.local'), `${envBuild}\n`, 'utf8');

console.log(`[build-meta] APP_BUILD_ID=${buildId} NAV_CONFIG_VERSION=${navConfigVersion}`);
